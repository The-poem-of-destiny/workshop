  "  const outdated = Array.isArray(health?.outdated) ? health.outdated : [];",
  "  if (!outdated.length) { showToast('当前没有已知脚本依赖需要更新'); return null; }",
  "  const rows = outdated.map((item, index) => {",
  "    const installed = item?.installedVersion ? `v${item.installedVersion}` : '未知版本';",
