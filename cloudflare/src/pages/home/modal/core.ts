  "    return `<section class=\"dependency-health-item\"><div class=\"dependency-health-heading\"><strong>${escapeHtml(name)}</strong><span>${escapeHtml(installed)} <i class=\"fas fa-arrow-right\"></i> ${escapeHtml(latest)}</span></div><p>Workshop 只检测到版本较旧，不会自动修改你的酒馆助手脚本。</p>${codeHtml}</section>`;",
