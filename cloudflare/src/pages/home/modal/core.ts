  "    const name = item?.dependencyName || item?.scriptName || '脚本依赖';",
  "    const suggestedUrl = getScriptDependencySuggestedImport(item);",
  "    const updateCode = suggestedUrl ? `import '${suggestedUrl}'` : '';",
  "    const codeHtml = updateCode",
  "      ? `<div class=\"release-update-codebox dependency-update-codebox\"><textarea class=\"release-update-code dependency-update-code\" readonly spellcheck=\"false\">${escapeHtml(updateCode)}</textarea><button class=\"release-update-copy-btn\" type=\"button\" data-dependency-copy=\"${index}\" aria-label=\"复制新版 import\"><i class=\"fas fa-copy\"></i><span>复制</span></button></div>`",
