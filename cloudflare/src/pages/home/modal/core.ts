  'function bindSafeExternalLinkButtons(root) {',
  '  if (!root?.querySelectorAll) return;',
  '  root.querySelectorAll("[data-external-url]").forEach(button => {',
  '    if (button.dataset.externalUrlBound === "1") return;',
  '    button.dataset.externalUrlBound = "1";',
  '    button.addEventListener("click", event => {',
  '      event.preventDefault();',
  '      event.stopPropagation();',
  '      openExternalLinkWarning(button.dataset.externalUrl || "");',
  '    });',
  '  });',
  '}',
